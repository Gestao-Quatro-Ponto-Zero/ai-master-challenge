const SPARKLE = '<path d="M12 2l2.4 7.6L22 12l-7.6 2.4L12 22l-2.4-7.6L2 12l7.6-2.4z" fill="currentColor" stroke="currentColor" stroke-linejoin="round"/>';

// icon('target', { size: 17, stroke: 1.7, label: 'Foco' }) -> SVG (decorativo sem label).
export function icon(name, { size = 18, stroke = 1.8, label = '' } = {}) {
  const body = name === 'sparkle' ? SPARKLE : PATHS[name];
  if (!body) return raw('');
  const a11y = label ? `role="img" aria-label="${escapeHtml(label)}"` : 'aria-hidden="true" focusable="false"';
  const paint = name === 'sparkle'
    ? ''
    : ` fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round"`;
  return raw(`<svg width="${size}" height="${size}" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg" ${a11y}${paint}>${body}</svg>`);
}
