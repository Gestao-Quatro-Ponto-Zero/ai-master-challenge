-- 0002_config_usuarios.sql  [LOTE 1]
-- Usuários (users) escolhidos na tela, sem login (decisões 12 e 15). O "profile" é o papel do usuário
-- (vendedor, manager, admin, sistema), com o vínculo ao vendedor ou ao manager do time: não há tabela de
-- perfis separada. Também cria os parâmetros e as funções de leitura de parâmetro.

create table config_usuarios (
  id            bigint generated by default as identity primary key,  -- "by default": a carga fixa os ids
  papel         text not null check (papel in ('vendedor', 'manager', 'admin', 'sistema')),
  nome_exibicao text not null check (char_length(btrim(nome_exibicao)) between 1 and 120),
  vendedor_nome text unique references core_vendedores (nome) on delete restrict,
  manager_nome  text unique references core_managers (nome) on delete restrict,
  ativo         boolean not null default true,
  criado_em     timestamptz not null default now(),
  constraint config_usuarios_papel_chave_chk check (
    (papel = 'vendedor' and vendedor_nome is not null and manager_nome is null) or
    (papel = 'manager' and manager_nome is not null and vendedor_nome is null) or
    (papel in ('admin', 'sistema') and vendedor_nome is null and manager_nome is null)
  )
);
-- vendedor_nome e manager_nome já têm índice pela restrição unique.

create table config_parametros (
  chave         text primary key check (chave ~ '^[a-z][a-z0-9_]*$'),
  valor         jsonb not null,
  descricao     text not null,
  atualizado_em timestamptz not null default now()
);

-- Leitura de parâmetros
create or replace function config_valor(p_chave text) returns jsonb
language sql stable set search_path = public as $$
  select valor from config_parametros where chave = p_chave
$$;

create or replace function config_texto(p_chave text) returns text
language sql stable set search_path = public as $$
  select config_valor(p_chave) #>> '{}'
$$;

create or replace function config_inteiro(p_chave text) returns integer
language sql stable set search_path = public as $$
  select (config_valor(p_chave) #>> '{}')::integer
$$;

create or replace function config_booleano(p_chave text) returns boolean
language sql stable set search_path = public as $$
  select coalesce((config_valor(p_chave) #>> '{}')::boolean, false)
$$;

create or replace function config_lista(p_chave text) returns text[]
language sql stable set search_path = public as $$
  select coalesce(array(select jsonb_array_elements_text(config_valor(p_chave))), '{}'::text[])
$$;
