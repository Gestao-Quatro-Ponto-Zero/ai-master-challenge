import pandas as pd, sys
D = sys.argv[1]
p = pd.read_csv(f"{D}/sales_pipeline.csv"); a = pd.read_csv(f"{D}/accounts.csv")
pr = pd.read_csv(f"{D}/products.csv"); t = pd.read_csv(f"{D}/sales_teams.csv")
print(p.shape, p.dtypes.to_dict())
print(p.deal_stage.value_counts(dropna=False))
print("null per col:\n", p.isna().sum())
print("null account by stage:\n", p[p.account.isna()].deal_stage.value_counts())
print("null engage by stage:\n", p[p.engage_date.isna()].deal_stage.value_counts())
print("products in pipeline not in catalog:", set(p['product']) - set(pr['product']))
print("catalog not in pipeline:", set(pr['product']) - set(p['product']))
print("agents in pipeline not in teams:", set(p.sales_agent) - set(t.sales_agent))
print("teams agents w/o deals:", set(t.sales_agent) - set(p.sales_agent))
print("accounts not in table:", set(p.account.dropna()) - set(a.account))
print("sectors:", a.sector.value_counts().to_dict())
print("locations:", a.office_location.value_counts().to_dict())
print("subsidiary:", a.subsidiary_of.notna().sum())
for c in ['engage_date','close_date']: p[c]=pd.to_datetime(p[c])
print("engage range", p.engage_date.min(), p.engage_date.max())
print("close range", p.close_date.min(), p.close_date.max())
print("dup ids:", p.opportunity_id.duplicated().sum())
print(t.groupby(['regional_office','manager']).size())
print(pr)
